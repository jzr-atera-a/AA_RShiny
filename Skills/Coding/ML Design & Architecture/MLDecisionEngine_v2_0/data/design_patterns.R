# ── Scoring function ──────────────────────────────────────────────────────────
score_patterns <- function(ml_system_ids=NULL, problem_type=NULL,
                           data_type=NULL, latency=NULL,
                           team_maturity=NULL, compliance=NULL) {
  scores <- sapply(DESIGN_PATTERNS, function(p) {
    s <- 0
    # Primary match: ML system directly referenced in pattern
    if(!is.null(ml_system_ids))
      s <- s + sum(ml_system_ids %in% p$ml_system_ids) * 4
    if(!is.null(problem_type)  && problem_type  %in% p$problem_types)  s <- s + 3
    if(!is.null(data_type)     && data_type      %in% p$data_types)    s <- s + 2
    if(!is.null(latency)       && latency        %in% p$latency)       s <- s + 2
    if(!is.null(team_maturity) && team_maturity  %in% p$team_maturity) s <- s + 1

    # Compliance bonuses
    if(!is.null(compliance)) {
      if(("gdpr" %in% compliance || "fca" %in% compliance) &&
         p$id %in% c("RA-02","RA-03","RS-03","RE-07")) s <- s + 3
      if("avact" %in% compliance &&
         p$id %in% c("RA-02","RA-03","RS-03","PR-05")) s <- s + 3
    }
    s
  })
  idx <- order(scores, decreasing=TRUE)
  list(top3=DESIGN_PATTERNS[idx[1:min(3,length(idx))]], all=DESIGN_PATTERNS[idx], scores=scores[idx])
}

